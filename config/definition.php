<?php

declare(strict_types=1);

namespace Symfony\Component\Config\Definition\Configurator;

use Flawe\FlareBundle\FlareConfig;
use Flawe\FlareBundle\Sampling\Rules\RuleType;
use Flawe\FlareBundle\Senders\SenderType;

return static function (DefinitionConfigurator $definition): void {
    $definition->rootNode()
        ->children()
            ->scalarNode('key')
                ->info('Flare project API key. Flare is disabled when empty.')
                ->defaultNull()
            ->end()
            ->booleanNode('use_defaults')
                ->info('Enable Flare\'s default collected data before applying the "collect" options.')
                ->defaultTrue()
            ->end()
            ->enumNode('subtasks')
                ->info('Trace each request as a subtask. "auto" enables subtasks in long-running processes (FrankenPHP worker, RoadRunner).')
                ->values(['auto', 'always', 'never'])
                ->defaultValue('auto')
            ->end()
            ->booleanNode('disable_api_queue')
                ->info('Send payloads immediately instead of queueing them until the end of the request or command.')
                ->defaultFalse()
            ->end()
            ->arrayNode('log')
                ->info('Send application logs to Flare.')
                ->children()
                    ->booleanNode('enable')
                        ->info('Send logs to Flare. Defaults to Flare\'s setting (disabled).')
                    ->end()
                    ->booleanNode('auto_register')
                        ->info('Hook into the Symfony logger: registers a "flare" Monolog handler with MonologBundle, decorates the "logger" service otherwise.')
                        ->defaultTrue()
                    ->end()
                    ->enumNode('minimal_level')
                        ->info('Minimal level of the logs sent to Flare.')
                        ->values(FlareConfig::LOG_LEVELS)
                    ->end()
                ->end()
            ->end()
            ->booleanNode('report')
                ->info('Report errors to Flare. Defaults to Flare\'s setting (enabled).')
            ->end()
            ->integerNode('report_error_levels')
                ->info('PHP error levels to report, as an E_* bitmask. Defaults to Flare\'s setting.')
            ->end()
            ->booleanNode('trace')
                ->info('Send performance traces to Flare. Defaults to Flare\'s setting (enabled).')
            ->end()
            ->arrayNode('trace_limits')
                ->info('Limits applied to each trace. Missing limits use Flare\'s defaults.')
                ->children()
                    ->integerNode('max_spans')->info('Maximum number of spans per trace.')->end()
                    ->integerNode('max_attributes_per_span')->info('Maximum number of attributes per span.')->end()
                    ->integerNode('max_span_events_per_span')->info('Maximum number of events per span.')->end()
                    ->integerNode('max_attributes_per_span_event')->info('Maximum number of attributes per span event.')->end()
                    ->integerNode('max_attribute_size_in_kb')->info('Maximum size of an attribute, in KB.')->end()
                ->end()
            ->end()
            ->arrayNode('sampling')
                ->info('Trace sampling. Defaults to Flare\'s setting (10% of traces).')
                ->validate()
                    ->ifTrue(static fn (mixed $sampling): bool => \is_array($sampling) && $sampling['strategy'] !== 'rate' && $sampling['rules'] !== [])
                    ->thenInvalid('Sampling rules require the "rate" strategy.')
                ->end()
                ->children()
                    ->enumNode('strategy')
                        ->info('Sample traces at "rate", or "always" / "never" sample them.')
                        ->values(['always', 'never', 'rate'])
                        ->defaultValue('rate')
                    ->end()
                    ->floatNode('rate')
                        ->info('Base sampling rate, between 0 and 1.')
                        ->min(0)->max(1)
                    ->end()
                    ->arrayNode('rules')
                        ->info('Per-entry-point sampling rates, overriding the base rate.')
                        ->arrayPrototype()
                            ->children()
                                ->enumNode('type')
                                    ->info('Entry point type. "route" matches the Symfony route name.')
                                    ->values(array_map(static fn (RuleType $type): string => $type->value, RuleType::cases()))
                                    ->isRequired()
                                ->end()
                                ->scalarNode('pattern')
                                    ->info('Entry point pattern, "*" being a wildcard.')
                                    ->isRequired()
                                    ->cannotBeEmpty()
                                ->end()
                                ->floatNode('rate')
                                    ->info('Sampling rate of the matching entry points, between 0 and 1.')
                                    ->isRequired()
                                    ->min(0)->max(1)
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('sender')
                ->info('Transport used to send payloads to Flare. Accepts the sender type as a shortcut.')
                ->beforeNormalization()
                    ->ifString()
                    ->then(static fn (string $type): array => ['type' => $type])
                ->end()
                ->children()
                    ->enumNode('type')
                        ->info('Sender type.')
                        ->values(array_map(static fn (SenderType $type): string => $type->value, SenderType::cases()))
                        ->defaultValue(SenderType::CURL->value)
                        ->validate()
                            ->ifTrue(static fn (mixed $type): bool => $type === SenderType::GUZZLE->value && !class_exists('GuzzleHttp\Client'))
                            ->thenInvalid('The %s sender requires the "guzzlehttp/guzzle" package.')
                        ->end()
                    ->end()
                    ->arrayNode('options')
                        ->info('Options passed to the sender.')
                        ->normalizeKeys(false)
                        ->variablePrototype()->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('collect')
                ->info('Data collected by Flare. Missing options use Flare\'s defaults.')
                ->children()
                    ->booleanNode('errors_with_traces')->info('Attach errors to the current trace.')->end()
                    ->booleanNode('dumps')->info('Collect dump() calls.')->end()
                    ->booleanNode('context')->info('Collect context data.')->end()
                    ->booleanNode('commands')->info('Collect console commands.')->end()
                    ->booleanNode('requests')->info('Collect HTTP requests.')->end()
                    ->booleanNode('cache_events')->info('Collect cache events.')->end()
                    ->booleanNode('logs_with_errors')->info('Attach logs to error reports. Requires log.enable.')->end()
                    ->booleanNode('queries')->info('Collect database queries.')->end()
                    ->booleanNode('transactions')->info('Collect database transactions.')->end()
                    ->booleanNode('external_http')->info('Collect outgoing HTTP requests.')->end()
                    ->booleanNode('filesystem_operations')->info('Collect filesystem operations.')->end()
                    ->booleanNode('git_info')->info('Collect git information of the application.')->end()
                    ->booleanNode('views')->info('Collect view rendering.')->end()
                    ->booleanNode('glows')->info('Collect glows added with $flare->glow().')->end()
                    ->booleanNode('stack_frame_arguments')->info('Collect the arguments of stack frames.')->end()
                    ->booleanNode('server_info')->info('Collect server information.')->end()
                ->end()
            ->end()
            ->arrayNode('censor')
                ->info('Data censored before being sent to Flare. Missing options use Flare\'s defaults.')
                ->children()
                    ->booleanNode('client_ips')->info('Censor client IP addresses.')->end()
                    ->booleanNode('cookies')->info('Censor cookies.')->end()
                    ->booleanNode('session')->info('Censor session data.')->end()
                    ->arrayNode('headers')
                        ->info('Names of the headers to censor.')
                        ->scalarPrototype()->end()
                    ->end()
                    ->arrayNode('body_fields')
                        ->info('Names of the request body fields to censor.')
                        ->scalarPrototype()->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('application')
                ->info('Application metadata attached to every payload.')
                ->children()
                    ->stringNode('version')->info('Application version.')->end()
                    ->stringNode('name')->info('Application name.')->end()
                    ->stringNode('stage')->info('Application stage, e.g. "production".')->end()
                    ->stringNode('path')->info('Application root path, used to shorten file paths.')->end()
                ->end()
            ->end()
        ->end()
    ->end()
    ;
};
