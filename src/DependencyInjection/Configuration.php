<?php

declare(strict_types=1);

namespace Flawe\FlareBundle\DependencyInjection;

use Flawe\FlareBundle\FlareConfig;
use Flawe\FlareBundle\Sampling\Rules\RuleType;
use Flawe\FlareBundle\Senders\SenderType;
use Spatie\FlareClient\Senders\Sender;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    #[\Override]
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('flare');

        $rootNode = $treeBuilder->getRootNode();
        $rootNode
            ->children()
                ->scalarNode('key')->defaultNull()->end()
                ->booleanNode('use_defaults')->defaultTrue()->end()
                ->enumNode('subtasks')
                    ->values(['auto', 'always', 'never'])
                    ->defaultValue('auto')
                ->end()
                ->booleanNode('disable_api_queue')->defaultFalse()->end()
                ->arrayNode('log')
                    ->children()
                        ->booleanNode('enable')->end()
                        ->booleanNode('auto_register')->defaultTrue()->end()
                        ->enumNode('minimal_level')
                            ->values(FlareConfig::LOG_LEVELS)
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('report')->end()
                ->integerNode('report_error_levels')->end()
                ->booleanNode('trace')->end()
                ->arrayNode('trace_limits')
                    ->children()
                        ->integerNode('max_spans')->end()
                        ->integerNode('max_attributes_per_span')->end()
                        ->integerNode('max_span_events_per_span')->end()
                        ->integerNode('max_attributes_per_span_event')->end()
                        ->integerNode('max_attribute_size_in_kb')->end()
                    ->end()
                ->end()
                ->arrayNode('sampling')
                    ->validate()
                        ->ifTrue(static fn (mixed $sampling): bool => \is_array($sampling) && 'rate' !== $sampling['strategy'] && [] !== $sampling['rules'])
                        ->thenInvalid('Sampling rules require the "rate" strategy.')
                    ->end()
                    ->children()
                        ->enumNode('strategy')
                            ->values(['always', 'never', 'rate'])
                            ->defaultValue('rate')
                        ->end()
                        ->floatNode('rate')->min(0)->max(1)->end()
                        ->arrayNode('rules')
                            ->arrayPrototype()
                                ->children()
                                    ->enumNode('type')
                                        ->values(array_map(static fn (RuleType $type): string => $type->value, RuleType::cases()))
                                        ->isRequired()
                                    ->end()
                                    ->scalarNode('pattern')->isRequired()->cannotBeEmpty()->end()
                                    ->floatNode('rate')->isRequired()->min(0)->max(1)->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('sender')
                    ->beforeNormalization()
                        ->ifString()
                        ->then(static fn (string $type): array => ['type' => $type])
                    ->end()
                    ->children()
                        ->scalarNode('type')
                            ->defaultValue('curl')
                            ->validate()
                                ->ifTrue(static fn (mixed $type): bool => !\is_string($type) || null === SenderType::tryFrom($type))
                                ->thenInvalid('Invalid sender %s: expected "' . implode('", "', array_map(static fn (SenderType $type): string => $type->value, SenderType::cases())) . '" or a class implementing ' . Sender::class . '.')
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (mixed $type): bool => 'guzzle' === $type && !class_exists('GuzzleHttp\Client'))
                                ->thenInvalid('The %s sender requires the "guzzlehttp/guzzle" package.')
                            ->end()
                        ->end()
                        ->arrayNode('options')
                            ->normalizeKeys(false)
                            ->variablePrototype()->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('collect')
                    ->children()
                        ->booleanNode('errors_with_traces')->end()
                        ->booleanNode('dumps')->end()
                        ->booleanNode('context')->end()
                        ->booleanNode('commands')->end()
                        ->booleanNode('requests')->end()
                        ->booleanNode('cache_events')->end()
                        ->booleanNode('logs_with_errors')->end()
                        ->booleanNode('queries')->end()
                        ->booleanNode('transactions')->end()
                        ->booleanNode('external_http')->end()
                        ->booleanNode('filesystem_operations')->end()
                        ->booleanNode('git_info')->end()
                        ->booleanNode('views')->end()
                        ->booleanNode('glows')->end()
                        ->booleanNode('stack_frame_arguments')->end()
                        ->booleanNode('server_info')->end()
                    ->end()
                ->end()
                ->arrayNode('censor')
                    ->children()
                        ->booleanNode('client_ips')->end()
                        ->booleanNode('cookies')->end()
                        ->booleanNode('session')->end()
                        ->arrayNode('headers')
                            ->scalarPrototype()->end()
                        ->end()
                        ->arrayNode('body_fields')
                            ->scalarPrototype()->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('application')
                    ->children()
                        ->stringNode('version')->end()
                        ->stringNode('name')->end()
                        ->stringNode('stage')->end()
                        ->stringNode('path')->end()
                    ->end()
                ->end()
            ->end()
        ->end()
        ;

        return $treeBuilder;
    }
}
